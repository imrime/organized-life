#!/usr/bin/env python3
"""Content-hash immutable assets (docs/spec/06-pwa-release.md §2.4).

For every file in assets-src/ (images, sounds, fonts, SVG):
  assets-src/<dir>/<name>.<ext>  →  assets/<dir>/<name>.<hash8>.<ext>   (sha-256, first 8 hex chars)
Then:
  * removes stale hashed files from assets/,
  * writes js/asset-manifest.js  (logical path → hashed URL),
  * rewrites the IMMUTABLE_ASSETS block in sw.js (hashed assets + js/vendor/* files).
Idempotent; stdlib only.
"""
import hashlib
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets-src")
OUT = os.path.join(ROOT, "assets")
VENDOR = os.path.join(ROOT, "js", "vendor")
MANIFEST = os.path.join(ROOT, "js", "asset-manifest.js")
SW = os.path.join(ROOT, "sw.js")
EXTENSIONS = {".webp", ".png", ".jpg", ".jpeg", ".svg", ".m4a", ".ogg", ".mp3", ".woff2"}
SKIP_DIRS = {"templates", "originals"}
BLOCK = re.compile(r"(// <immutable-assets>\n)(.*?)(// </immutable-assets>)", re.S)


def sha8(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            digest.update(chunk)
    return digest.hexdigest()[:8]


def main():
    mapping = {}
    if os.path.isdir(SRC):
        for dirpath, dirnames, filenames in os.walk(SRC):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
            for name in sorted(filenames):
                stem, ext = os.path.splitext(name)
                if ext.lower() not in EXTENSIONS:
                    continue
                src = os.path.join(dirpath, name)
                rel_dir = os.path.relpath(dirpath, SRC)
                hashed = f"{stem}.{sha8(src)}{ext.lower()}"
                dest_dir = os.path.join(OUT, rel_dir)
                os.makedirs(dest_dir, exist_ok=True)
                dest = os.path.join(dest_dir, hashed)
                if not os.path.exists(dest):
                    shutil.copyfile(src, dest)
                logical = os.path.normpath(os.path.join(rel_dir, name)).replace(os.sep, "/")
                mapping[logical] = "./" + os.path.relpath(dest, ROOT).replace(os.sep, "/")

    keep = {os.path.normpath(os.path.join(ROOT, url[2:])) for url in mapping.values()}
    removed = 0
    if os.path.isdir(OUT):
        for dirpath, _, filenames in os.walk(OUT):
            for name in filenames:
                path = os.path.normpath(os.path.join(dirpath, name))
                if name.startswith(".") or path in keep:
                    continue
                os.remove(path)
                removed += 1

    with open(MANIFEST, "w", encoding="utf-8") as fh:
        fh.write("// GENERATED by tools/hash_assets.py — do not edit. Logical asset path → content-hashed URL.\n")
        fh.write("export const assets = {\n")
        for logical in sorted(mapping):
            fh.write(f"  '{logical}': '{mapping[logical]}',\n")
        fh.write("};\n")

    vendor = []
    if os.path.isdir(VENDOR):
        vendor = [f"./js/vendor/{n}" for n in sorted(os.listdir(VENDOR)) if not n.startswith(".") and not n.endswith(".md")]
    immutable = vendor + sorted(mapping.values())
    source = open(SW, encoding="utf-8").read()
    if not BLOCK.search(source):
        print("sw.js: immutable markers not found")
        return 1
    body = "const IMMUTABLE_ASSETS = [\n" + "".join(f"  '{p}',\n" for p in immutable) + "];\n"
    source = BLOCK.sub(lambda m: m.group(1) + body + m.group(3), source)
    open(SW, "w", encoding="utf-8").write(source)
    print(f"hashed {len(mapping)} assets, removed {removed} stale, {len(immutable)} immutable entries in sw.js")
    return 0


if __name__ == "__main__":
    sys.exit(main())
